/**
 * Builds a minimal Japanese webfont for the UI.
 *
 * Shipping the whole Noto Sans JP is ~85 MB, so this script collects every
 * non-ASCII character the game actually renders, finds the @fontsource unicode
 * range subsets that cover them, and copies only those woff2 files plus a
 * matching @font-face stylesheet into public/fonts/.
 *
 * Usage: node scripts/build-font-subset.mjs   (requires @fontsource/noto-sans-jp
 *        to be installed, e.g. as a temporary dev dependency)
 */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import path from 'node:path';

const PKG = path.resolve('node_modules', '@fontsource', 'noto-sans-jp');
const OUT = path.resolve('public', 'fonts', 'noto-sans-jp');
const WEIGHTS = [400, 500, 700];

if (!existsSync(PKG)) {
  console.error('Noto Sans JP (fontsource) is not installed. Run: npm i -D @fontsource/noto-sans-jp');
  process.exit(1);
}

// ---- 1. collect every character the UI can render -------------------------
function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const p = path.join(dir, entry);
    const st = statSync(p);
    if (st.isDirectory()) {
      if (['node_modules', 'dist', '.git', 'verification'].includes(entry)) continue;
      walk(p, out);
    } else if (/\.(html|js|json|css)$/.test(entry)) {
      out.push(p);
    }
  }
  return out;
}

const chars = new Set();
for (const file of [...walk(path.resolve('src')), path.resolve('index.html'), path.resolve('public/maps/registry.json')]) {
  const text = readFileSync(file, 'utf8');
  for (const ch of text) chars.add(ch);
}
// always include the kana + digits so future strings render correctly
for (let c = 0x3040; c <= 0x30ff; c++) chars.add(String.fromCodePoint(c));

const codepoints = new Set();
for (const ch of chars) {
  const cp = ch.codePointAt(0);
  if (cp > 127) codepoints.add(cp);
}

// ---- 2. parse @font-face blocks and keep the ranges we need ---------------
function parseRange(str) {
  return str.split(',').map((part) => {
    const [a, b] = part.trim().replace(/^U\+/i, '').split('-');
    const start = parseInt(a, 16);
    const end = b ? parseInt(b, 16) : start;
    return [start, end];
  });
}

mkdirSync(OUT, { recursive: true });
let css = `/* Generated by scripts/build-font-subset.mjs - Noto Sans JP (SIL OFL 1.1) */\n`;
let copied = 0;
let bytes = 0;
const used = new Set();

for (const weight of WEIGHTS) {
  const cssPath = path.join(PKG, `${weight}.css`);
  const src = readFileSync(cssPath, 'utf8');
  const blocks = src.split('@font-face').slice(1);
  for (const block of blocks) {
    const rangeMatch = block.match(/unicode-range:\s*([^;]+);/);
    const urlMatch = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/);
    if (!rangeMatch || !urlMatch) continue;
    const ranges = parseRange(rangeMatch[1]);
    const needed = ranges.some(([a, b]) => {
      for (const cp of codepoints) if (cp >= a && cp <= b) return true;
      return false;
    });
    if (!needed) continue;
    const file = urlMatch[1];
    if (used.has(`${weight}/${file}`)) continue;
    used.add(`${weight}/${file}`);
    const from = path.join(PKG, 'files', file);
    if (!existsSync(from)) continue;
    copyFileSync(from, path.join(OUT, file));
    copied++;
    bytes += statSync(from).size;
    css += `@font-face{font-family:'Noto Sans JP';font-style:normal;font-weight:${weight};font-display:swap;src:url(./noto-sans-jp/${file}) format('woff2');unicode-range:${rangeMatch[1].trim()};}\n`;
  }
}

writeFileSync(path.resolve('public', 'fonts', 'noto-sans-jp.css'), css);
writeFileSync(path.resolve('public', 'fonts', 'OFL.txt'), readFileSync(path.join(PKG, 'LICENSE'), 'utf8'));
console.log(`[font] ${copied} woff2 files, ${(bytes / 1024).toFixed(0)} KB total, covering ${codepoints.size} codepoints`);
